/**
 * Truncate event descriptions for cards, hero banners, and previews.
 * Strips HTML tags and entities, enforces max character length (default 40),
 * and appends "..." if truncated. Full descriptions are read on the event landing page.
 */
/**
 * Strips HTML tags, removes scripts/styles, decodes HTML entities,
 * and collapses whitespace into clean plain text for SEO, Open Graph & social previews.
 */
export function stripHtml(text) {
  if (!text || typeof text !== "string") return "";
  return text
    // Remove script and style tags and their contents
    .replace(/<script[^>]*>[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[^>]*>[\s\S]*?<\/style>/gi, " ")
    // Remove footnote and source chips tags including contents if any
    .replace(/<source-footnote[^>]*>[\s\S]*?<\/source-footnote>/gi, " ")
    .replace(/<sources-carousel-inline[^>]*>[\s\S]*?<\/sources-carousel-inline>/gi, " ")
    .replace(/<source-inline-chip[^>]*>[\s\S]*?<\/source-inline-chip>/gi, " ")
    // Remove HTML comments
    .replace(/<!--[\s\S]*?-->/g, " ")
    // Remove all remaining HTML tags
    .replace(/<[^>]+>/g, " ")
    // Decode common named entities
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/&apos;/gi, "'")
    // Decode decimal entities &#123;
    .replace(/&#(\d+);/g, (_, dec) => {
      try {
        return String.fromCharCode(parseInt(dec, 10));
      } catch (e) {
        return "";
      }
    })
    // Decode hex entities &#x1f;
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => {
      try {
        return String.fromCharCode(parseInt(hex, 16));
      } catch (e) {
        return "";
      }
    })
    // Collapse all whitespace
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Truncate event descriptions for cards, hero banners, and previews.
 * Strips HTML tags and entities, enforces max character length (default 40),
 * and appends "..." if truncated. Full descriptions are read on the event landing page.
 */
export function truncateDescription(text, maxLength = 40) {
  if (!text || typeof text !== "string") return "";
  const clean = stripHtml(text);
  if (clean.length <= maxLength) return clean;
  return `${clean.slice(0, maxLength).trimEnd()}...`;
}

