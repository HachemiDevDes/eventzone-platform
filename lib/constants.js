export function getLocalizedIndustry(industry, langOrT = "en") {
  if (!industry || typeof industry !== "string") return industry || "";
  const trimmed = industry.trim();
  const key = "industry." + trimmed.toLowerCase().replace(/[^a-z0-9]/g, "_");

  // 1. If translation function t(key, fallback) is passed
  if (typeof langOrT === "function") {
    const res = langOrT(key, null);
    if (res && res !== key && res !== null) return res;
  }

  // 2. If language code string is passed (or direct lookup fallback)
  const lang = typeof langOrT === "string" ? langOrT : "en";
  if (lang === "ar") {
    if (INDUSTRY_TRANSLATIONS[trimmed]?.ar) return INDUSTRY_TRANSLATIONS[trimmed].ar;
    if (INDUSTRY_TRANSLATIONS[industry]?.ar) return INDUSTRY_TRANSLATIONS[industry].ar;
  }
  if (lang === "fr") {
    if (INDUSTRY_TRANSLATIONS[trimmed]?.fr) return INDUSTRY_TRANSLATIONS[trimmed].fr;
    if (INDUSTRY_TRANSLATIONS[industry]?.fr) return INDUSTRY_TRANSLATIONS[industry].fr;
  }

  return industry;
}

