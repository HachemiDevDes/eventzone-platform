/**
 * Finds matching equipment preset by item object, presetKey, or raw name/specs string.
 */
export function findEquipmentPreset(itemOrName) {
  if (!itemOrName) return null;
  const targetStr = typeof itemOrName === "string" 
    ? itemOrName.trim().toLowerCase() 
    : (itemOrName.name || itemOrName.presetKey || itemOrName.id || "").trim().toLowerCase();
  const presetKey = typeof itemOrName === "object" ? (itemOrName.presetKey || itemOrName.id) : null;

  return SPECIFIC_EQUIPMENT_PRESETS.find(p => {
    if (presetKey && (p.id === presetKey || p.presetKey === presetKey)) return true;
    if (!targetStr) return false;
    if (p.id.toLowerCase() === targetStr || p.name.toLowerCase() === targetStr) return true;
    if (p.translations?.fr?.name?.toLowerCase() === targetStr) return true;
    if (p.translations?.ar?.name?.toLowerCase() === targetStr) return true;
    if (typeof itemOrName === "string") {
      if (p.specs.toLowerCase() === targetStr) return true;
      if (p.translations?.fr?.specs?.toLowerCase() === targetStr) return true;
      if (p.translations?.ar?.specs?.toLowerCase() === targetStr) return true;
    }
    return false;
  }) || null;
}

/**
 * Returns the localized name for an equipment item or preset based on active language/i18n.
 */
export function getLocalizedEquipmentName(itemOrName, t = null, language = "en") {
  if (!itemOrName) return "";
  const rawName = typeof itemOrName === "string" ? itemOrName : (itemOrName.name || "");
  const preset = findEquipmentPreset(itemOrName);

  if (preset) {
    if (typeof t === "function") {
      const key = `logistics.preset_${preset.presetKey || preset.id}_name`;
      const trans = t(key);
      if (trans && trans !== key) return trans;
    }
    const langKey = (language || "en").slice(0, 2).toLowerCase();
    if (langKey === "ar" && preset.translations?.ar?.name) return preset.translations.ar.name;
    if (langKey === "fr" && preset.translations?.fr?.name) return preset.translations.fr.name;
    if (langKey === "en" && preset.name) return preset.name;
    if (preset.translations?.[langKey]?.name) return preset.translations[langKey].name;
    return preset.name || rawName;
  }

  return rawName;
}

/**
 * Returns the localized specifications for an equipment item or preset.
 */
export function getLocalizedEquipmentSpecs(itemOrSpecs, t = null, language = "en") {
  if (!itemOrSpecs) return "";
  const rawSpecs = typeof itemOrSpecs === "string" ? itemOrSpecs : (itemOrSpecs.specs || "");
  const preset = findEquipmentPreset(itemOrSpecs);

  if (preset) {
    if (typeof t === "function") {
      const key = `logistics.preset_${preset.presetKey || preset.id}_specs`;
      const trans = t(key);
      if (trans && trans !== key) return trans;
    }
    const langKey = (language || "en").slice(0, 2).toLowerCase();
    if (langKey === "ar" && preset.translations?.ar?.specs) return preset.translations.ar.specs;
    if (langKey === "fr" && preset.translations?.fr?.specs) return preset.translations.fr.specs;
    if (langKey === "en" && preset.specs) return preset.specs;
    if (preset.translations?.[langKey]?.specs) return preset.translations[langKey].specs;
    return preset.specs || rawSpecs;
  }

  return rawSpecs;
}

/**
 * Returns the localized category name for equipment items.
 */
export function getLocalizedEquipmentCategory(cat, t = null) {
  if (!cat) return "";
  const lower = String(cat).toLowerCase();
  const getT = (key, fallback) => (typeof t === "function" ? t(key, fallback) : fallback);

  if (lower.includes("furniture") || lower.includes("seating")) return getT("logistics.catFurniture", "Furniture & Seating");
  if (lower.includes("electrical") || lower.includes("power")) return getT("logistics.catElectrical", "Electrical & Power");
  if (lower.includes("audiovisual") || lower.includes("screen")) return getT("logistics.catAudiovisual", "Audiovisual & Screens");
  if (lower.includes("display") || lower.includes("signage")) return getT("logistics.catDisplaySignage", "Display & Signage");
  if (lower.includes("appliance") || lower.includes("comfort")) return getT("logistics.catAppliances", "Appliances & Comfort");
  if (lower.includes("other")) return getT("logistics.catOther", "Other Equipment");
  return cat;
}
