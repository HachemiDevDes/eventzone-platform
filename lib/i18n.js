const LanguageContext = createContext({
  lang: "en",
  setLang: () => {},
  t: (key, fallback) => fallback || key,
  isRTL: false,
  dir: "ltr",
  languages: [],
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    if (typeof window !== "undefined") {
      try {
        const saved = localStorage.getItem("app_language");
        if (saved && ["en", "fr", "ar"].includes(saved)) {
          return saved;
        }
      } catch (e) {}
    }
    return "en";
  });

  useEffect(() => {
    if (typeof window !== "undefined") {
      try {
        const savedLang = localStorage.getItem("app_language");
        if (savedLang && ["en", "fr", "ar"].includes(savedLang)) {
          setLangState(savedLang);
          document.documentElement.dir = savedLang === "ar" ? "rtl" : "ltr";
          document.documentElement.lang = savedLang;
        }
      } catch (e) {}
    }
  }, []);

  const setLang = (newLang) => {
    if (!["en", "fr", "ar"].includes(newLang)) return;
    if (newLang === lang) return;
    setLangState(newLang);
    if (typeof window !== "undefined") {
      try {
        localStorage.setItem("app_language", newLang);
        document.cookie = `app_language=${newLang}; path=/; max-age=31536000; SameSite=Lax`;
        document.documentElement.dir = newLang === "ar" ? "rtl" : "ltr";
        document.documentElement.lang = newLang;
      } catch (e) {}
      window.location.reload();
    }
  };

  const t = (key, fallback = "") => {
    const dict = translations[lang] || translations.en;
    if (dict && dict[key] !== undefined) {
      return dict[key];
    }
    const enDict = translations.en;
    if (enDict && enDict[key] !== undefined) {
      return enDict[key];
    }
    return fallback || key;
  };

  const isRTL = lang === "ar";
  const dir = isRTL ? "rtl" : "ltr";

  const languages = [
    { code: "en", label: "English", short: "EN", icon: "https://i.imgur.com/NXtMImD.png" },
    { code: "fr", label: "Français", short: "FR", icon: "https://i.imgur.com/yS9Hjy9.png" },
    { code: "ar", label: "العربية", short: "AR", icon: "https://i.imgur.com/MolxgOM.png" },
  ];

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, isRTL, dir, languages }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
